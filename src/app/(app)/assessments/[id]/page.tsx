"use client";
import { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";

export default function AssessmentDetailPage({ params }: { params: { id: string } }) {
  const router = useRouter();
  const [data, setData] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [reviewNote, setReviewNote] = useState("");

  useEffect(() => {
    fetch(`/api/assessments/${params.id}`)
      .then(res => res.json())
      .then(d => {
        if (d.error) throw new Error(d.error);
        setData(d);
      })
      .catch(e => setError(e.message));
  }, [params.id]);

  async function submitReview(decision: string) {
    setBusy(true); setError(null);
    try {
      const res = await fetch(`/api/assessments/${params.id}/review`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ decision, note: reviewNote })
      });
      const d = await res.json();
      if (!res.ok) throw new Error(d.error);
      router.push("/assessments");
      router.refresh();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }

  if (error && !data) return <div className="p-8 text-red-600 bg-red-50 rounded">{error}</div>;
  if (!data) return <div className="p-8 text-gray-500">Loading assessment...</div>;

  const { assessment, change } = data;

  return (
    <div className="space-y-8 max-w-4xl pb-12">
      <header>
        <Link href="/assessments" className="text-sm text-gray-500 hover:underline">← Back to Assessments</Link>
        <h1 className="text-3xl font-semibold tracking-tight mt-2">{change?.title || "Assessment"}</h1>
        <div className="flex gap-3 mt-2">
          <span className={`inline-block px-3 py-1 rounded-full text-xs font-semibold capitalize ${
            assessment.impact_level === "critical" ? "bg-red-600 text-white" :
            assessment.impact_level === "high" ? "bg-orange-500 text-white" :
            assessment.impact_level === "medium" ? "bg-yellow-400 text-black" :
            "bg-gray-200 text-gray-700"
          }`}>{assessment.impact_level} Impact</span>
          <span className="text-sm text-gray-600">
            Status: <span className="font-medium capitalize">{assessment.human_review_status.replace('_', ' ')}</span>
          </span>
          <span className="text-sm text-gray-600">
            AI Confidence: <span className="font-medium">{Math.round((assessment.ai_confidence ?? 0) * 100)}%</span>
          </span>
        </div>
      </header>

      {error && <p className="text-sm text-red-600 bg-red-50 p-3 rounded">{error}</p>}

      <section className="bg-white p-6 rounded-lg border">
        <h2 className="text-xs uppercase tracking-wider text-gray-500 font-semibold mb-2">AI Reasoning</h2>
        <p className="text-gray-800 leading-relaxed">{assessment.reasoning}</p>
      </section>

      <div className="grid grid-cols-2 gap-4">
        <section className="bg-white p-6 rounded-lg border">
          <h2 className="text-xs uppercase tracking-wider text-gray-500 font-semibold mb-2">Affected Departments</h2>
          <div className="flex flex-wrap gap-2">
            {assessment.affected_departments?.map((d: string) => (
              <span key={d} className="bg-gray-100 px-3 py-1 rounded-full text-sm">{d}</span>
            ))}
          </div>
        </section>
        <section className="bg-white p-6 rounded-lg border">
          <h2 className="text-xs uppercase tracking-wider text-gray-500 font-semibold mb-2">Affected Processes</h2>
          <div className="flex flex-wrap gap-2">
            {assessment.affected_processes?.map((p: string) => (
              <span key={p} className="bg-gray-100 px-3 py-1 rounded-full text-sm">{p}</span>
            ))}
          </div>
        </section>
      </div>

      <section className="bg-white p-6 rounded-lg border">
        <h2 className="text-xs uppercase tracking-wider text-gray-500 font-semibold mb-2">Recommended Actions</h2>
        <ul className="list-disc pl-5 space-y-1 text-gray-800">
          {assessment.recommended_actions?.map((a: string, i: number) => <li key={i}>{a}</li>)}
        </ul>
      </section>

      {assessment.human_review_status === "pending" && (
        <section className="bg-gray-900 text-white p-6 rounded-lg">
          <h2 className="text-lg font-semibold mb-2">Human Review Required</h2>
          <p className="text-sm text-gray-300 mb-4">
            This assessment was generated by AI. Review the reasoning and recommended actions before approving.
          </p>
          <textarea
            value={reviewNote}
            onChange={(e) => setReviewNote(e.target.value)}
            placeholder="Optional: reviewer notes..."
            className="w-full rounded bg-gray-800 border border-gray-700 p-3 text-sm text-white mb-3"
            rows={2}
          />
          <div className="flex gap-2">
            <button onClick={() => submitReview("approved")} disabled={busy}
              className="rounded bg-green-500 text-white px-5 py-2 font-medium hover:bg-green-600 disabled:opacity-50">
              Approve
            </button>
            <button onClick={() => submitReview("rejected")} disabled={busy}
              className="rounded bg-red-500 text-white px-5 py-2 font-medium hover:bg-red-600 disabled:opacity-50">
              Reject
            </button>
          </div>
        </section>
      )}

      {assessment.human_review_status !== "pending" && (
        <section className="bg-white p-6 rounded-lg border">
          <p className="text-sm text-gray-600">
            This assessment was <span className="font-semibold">{assessment.human_review_status}</span>.
          </p>
        </section>
      )}
    </div>
  );
}